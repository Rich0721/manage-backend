CREATE TABLE tb_orders_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_id VARCHAR(10) NOT NULL,
    product_id VARCHAR(13) NOT NULL,
    quantity INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    discount NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(256) NOT NULL,
    CONSTRAINT pk_tb_orders_items PRIMARY KEY (id),
    CONSTRAINT uk_tb_orders_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_tb_orders_items_quantity CHECK (quantity > 0),
    CONSTRAINT fk_tb_orders_items_order_id
        FOREIGN KEY (order_id) REFERENCES tb_orders (id),
    CONSTRAINT fk_tb_orders_items_product_id
        FOREIGN KEY (product_id) REFERENCES tb_products (id),
    CONSTRAINT fk_tb_orders_items_created_by
        FOREIGN KEY (created_by) REFERENCES tb_users (uid)
);

COMMENT ON TABLE tb_orders_items IS 'Items recorded for each sales order';
COMMENT ON COLUMN tb_orders_items.id IS 'Internal order item identifier';
COMMENT ON COLUMN tb_orders_items.order_id IS 'Parent order identifier';
COMMENT ON COLUMN tb_orders_items.product_id IS 'Sold product identifier';
COMMENT ON COLUMN tb_orders_items.quantity IS 'Quantity sold';
COMMENT ON COLUMN tb_orders_items.price IS 'Unit price before discount';
COMMENT ON COLUMN tb_orders_items.discount IS 'Unit price after discount';
COMMENT ON COLUMN tb_orders_items.created_at IS 'UTC item creation timestamp';
COMMENT ON COLUMN tb_orders_items.created_by IS 'UID of the item creator';
